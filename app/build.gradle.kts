plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

android {
    namespace = "com.alexwing.urscreen"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.alexwing.urscreen"
        minSdk = 26
        targetSdk = 35
        // La release de GitHub los pasa con -PversionName=1.2.3 -PversionCode=<n>; en local valen estos.
        versionCode = (project.findProperty("versionCode") as String?)?.toIntOrNull() ?: 1
        versionName = (project.findProperty("versionName") as String?) ?: "1.0.0"
    }

    // La clave de firma NO está en el repositorio: se lee del entorno (en GitHub, de los secretos del repositorio).
    // Sin ella, `assembleRelease` genera un APK sin firmar.
    val keystorePath = System.getenv("URSCREEN_KEYSTORE_FILE")
    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("URSCREEN_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("URSCREEN_KEY_ALIAS")
                keyPassword = System.getenv("URSCREEN_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (keystorePath != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    buildFeatures {
        compose = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        unitTests.all {
            // Para ver las medidas de LiveServerTest en la salida de Gradle.
            it.testLogging.showStandardStreams = true
        }
    }
}

